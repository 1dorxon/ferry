#!/bin/sh
# Deploy BrowserDrop to Cloudflare. Computes the asset version (so browsers and
# the edge can never serve stale JS) and deploys with the scoped token.
set -eu
cd "$(dirname "$0")"
H=$(cat ../public/app.js ../public/style.css ../public/sw.js | sha256sum | cut -c1-12)
printf "// generated by deploy.sh -- content hash of app.js + style.css + sw.js\nexport const ASSET_VERSION = '%s';\n" "$H" > src/version.js
# The API token, if kept in a file (else wrangler uses its own login).
CF_ENV=${FERRY_CF_ENV:-$HOME/.luitlabs-secrets/cloudflare-account.env}
if [ -f "$CF_ENV" ]; then set -a; . "$CF_ENV"; set +a; fi
npx wrangler deploy "$@"
